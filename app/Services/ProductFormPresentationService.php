<?php

namespace App\Services;

use App\Models\Shop;

/**
 * Small, additive form contract shared by the Web and Android clients.
 * It describes UX defaults only; the existing request policies remain the
 * authorization and inventory-integrity boundary.
 */
class ProductFormPresentationService
{
    /** @param array<string, mixed> $profile @return array<string, mixed> */
    public function resolve(Shop $shop, array $profile): array
    {
        $type = $profile['business_type'] ?? 'general_retail';
        $archetype = config("business-types.type_archetypes.{$type}", 'general_retail');
        $capabilities = $profile['capabilities'] ?? [];
        $fields = $profile['product_fields'] ?? [];
        $enabled = static fn (string $key): bool => ($capabilities[$key] ?? 'disabled') === 'enabled';

        $saleUnits = [];
        if ($enabled('products')) {
            $saleUnits[] = 'unit';
        }
        // Bottle/ml are product-level choices, not global options for every
        // store. A non-perfumery shop may still use them when Decants is an
        // explicitly enabled capability (for a perfume item in a mixed shop).
        if ($enabled('perfume_fields') || $enabled('decants')) {
            if ($enabled('products')) {
                $saleUnits = [...$saleUnits, 'bottle', 'ml'];
            }
        }
        if ($enabled('services')) {
            $saleUnits[] = 'service';
        }
        if ($enabled('decants') && $enabled('products')) {
            $saleUnits[] = 'decant';
        }

        $defaultSaleUnit = match (true) {
            $archetype === 'fragrance' && in_array('bottle', $saleUnits, true) => 'bottle',
            $archetype === 'service_retail' && in_array('service', $saleUnits, true) => 'service',
            $saleUnits === ['service'] => 'service',
            in_array('unit', $saleUnits, true) => 'unit',
            default => $saleUnits[0] ?? 'unit',
        };

        $labels = [
            'unit' => match ($archetype) {
                'appliances' => 'Electrodoméstico completo',
                'footwear' => 'Artículo completo (ej.: un par)',
                'fragrance' => 'Producto completo',
                default => 'Artículo completo',
            },
            'bottle' => 'Botella completa',
            'ml' => 'Por mililitro (ml)',
            'service' => 'Servicio (sin inventario físico)',
        ];

        $unitKeys = [];
        foreach ($saleUnits as $saleUnit) {
            $unitKeys[$saleUnit] = match ($saleUnit) {
                'bottle' => 'bottle',
                'ml' => 'ml',
                'decant' => 'decant',
                'service' => 'service',
                default => 'unit',
            };
        }

        $unitUuids = [];
        foreach (array_unique(array_values($unitKeys)) as $key) {
            // This is the existing server-generated built-in taxonomy identity.
            // It is accepted by CatalogTaxonomyAccessService without creating a
            // new taxonomy record and is stable for the lifetime of this shop.
            $unitUuids[$key] = app(ShopRecordSyncService::class)->localId($shop, 'unit', $key);
        }

        // `supported_fields` is the intersection of fields that both product
        // forms can collect and persist today. Business config may request
        // additional fields, but that alone is not proof of Android parity.
        $supportedFields = ['name', 'category', 'photo', 'price', 'description'];
        // `model` is currently represented only through optional dynamic
        // attributes; it is not a stable product field on both clients.
        // Do not advertise it as a guaranteed form field until that contract
        // is persisted consistently by Web and Android.
        // Internal code/SKU is generated by the domain rather than entered as
        // a common create-form field. Brand and barcode are currently only
        // editable through Web (Android reads them from the API but its shared
        // ProductInput does not persist edits); expose their real state below.
        if ($enabled('inventory')) {
            $supportedFields = [...$supportedFields, 'stock', 'low_stock_threshold'];
        }
        if ($enabled('perfume_fields') || $enabled('decants')) {
            $supportedFields[] = 'volume_ml';
        }
        if ($enabled('services')) {
            $supportedFields[] = 'service_description';
        }
        if ($enabled('products')) {
            $supportedFields[] = 'combo';
        }

        return [
            'schema_version' => 1,
            'default_sale_unit' => $defaultSaleUnit,
            'available_sale_units' => array_values(array_unique($saleUnits)),
            'sale_unit_labels' => array_intersect_key($labels, array_flip($saleUnits)),
            'default_inventory_unit_key' => $unitKeys[$defaultSaleUnit] ?? 'unit',
            'sale_unit_to_inventory_unit' => $unitKeys,
            'inventory_unit_labels' => [
                'unit' => 'Unidades',
                'bottle' => 'Botellas',
                'ml' => 'Mililitros (ml)',
                'decant' => 'Decants',
                'service' => 'Servicios',
            ],
            'inventory_unit_uuids' => $unitUuids,
            'supported_fields' => array_values(array_unique($supportedFields)),
            'web_only_fields' => array_values(array_filter(
                ['brand', 'barcode'],
                fn (string $field): bool => in_array($field, $fields, true)
                    && $enabled($field),
            )),
            'feature_states' => [
                'brand' => in_array('brand', $fields, true) && $enabled('brand') ? 'web_only' : 'unsupported',
                'barcode' => in_array('barcode', $fields, true) && $enabled('barcode') ? 'web_only' : 'unsupported',
                'sku' => in_array('sku', $fields, true) && $enabled('sku') ? 'generated' : 'unsupported',
                'cost_price' => in_array('cost_price', $fields, true) && $enabled('inventory') ? 'permission_gated' : 'unsupported',
                'wholesale_price' => $enabled('wholesale') ? 'permission_gated' : 'unsupported',
                'model' => 'unsupported',
                'variants' => 'unsupported',
                'sizes' => 'unsupported',
                'colors' => 'unsupported',
                'serial_tracking' => 'unsupported',
                'weighted_products' => 'unsupported',
                'warranty_tracking' => 'unsupported',
            ],
            'allow_advanced_unit_override' => true,
            'profile_source' => 'server',
        ];
    }
}
